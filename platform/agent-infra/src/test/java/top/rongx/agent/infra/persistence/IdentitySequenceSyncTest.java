package top.rongx.agent.infra.persistence;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * 搬行后自增序列对齐。
 *
 * <p>真实故障是 PostgreSQL 的 {@code token_usage_pkey} 冲突：行带显式 id 复制过去之后，
 * identity 序列还停在旧值，应用下一次自增插入撞上已存在的行。序列属于 PostgreSQL 才有，
 * 本机测试环境不起 PG，因此这里覆盖三件不依赖 PG 的事：
 * <ul>
 *   <li>拨正语句的形状（{@code setval(MAX + 1, is_called=false)}，标识符加引号）；</li>
 *   <li>非 PG 目标库必须静默跳过，不能把已经成功的行复制判成失败；</li>
 *   <li>SQLite 目标库本来就自愈（显式 rowid 会抬高 {@code sqlite_sequence}），留作回归证据。</li>
 * </ul>
 */
class IdentitySequenceSyncTest {

    @TempDir
    Path tempDir;

    @AfterEach
    void cleanup() {
        PlatformDb.closeAll();
    }

    @Test
    @DisplayName("拨正语句：下一个 nextval 恰好是 MAX(id)+1")
    void setvalSqlBumpsPastMaxId() {
        assertEquals(
                "SELECT setval(?::regclass, COALESCE((SELECT MAX(\"id\") FROM \"token_usage\"), 0) + 1, false)",
                IdentitySequenceSync.setvalSql("token_usage", "id"),
                "is_called=false + MAX+1 才能让下一次自增拿到 MAX+1");
    }

    @Test
    @DisplayName("标识符统一加引号：混合大小写与内嵌引号都不会拼坏 SQL")
    void setvalSqlQuotesIdentifiers() {
        assertEquals(
                "SELECT setval(?::regclass, COALESCE((SELECT MAX(\"seq\") FROM \"Mixed\"\"Table\"), 0) + 1, false)",
                IdentitySequenceSync.setvalSql("Mixed\"Table", "seq"));
    }

    @Test
    @DisplayName("SQLite 目标库不参与对齐：识别不了 PG 序列，静默跳过")
    void sqliteTargetIsSkipped() throws Exception {
        try (Connection target = sqlite(tempDir.resolve("plain.db"));
             Statement statement = target.createStatement()) {
            statement.execute("CREATE TABLE token_usage ("
                    + "id integer PRIMARY KEY AUTOINCREMENT, session_id text NOT NULL)");

            assertFalse(IdentitySequenceSync.required(target), "SQLite 没有独立序列可拨");
            assertEquals(0, IdentitySequenceSync.sync(target, "token_usage"), "非 PG 目标必须返回 0");
            assertEquals(0, IdentitySequenceSync.sync(target, "不存在的表"), "缺表也不能抛");
        }
    }

    @Test
    @DisplayName("SQLite 搬行后自增天然接在最大值后面，无需对齐")
    void sqliteCopyLeavesAutoincrementUsable() throws Exception {
        Path sourceFile = tempDir.resolve("source.db");
        Path targetFile = tempDir.resolve("target.db");
        try (Connection source = sqlite(sourceFile);
             Statement statement = source.createStatement()) {
            statement.execute("CREATE TABLE token_usage ("
                    + "id integer PRIMARY KEY AUTOINCREMENT, session_id text NOT NULL)");
            statement.execute("INSERT INTO token_usage (id, session_id) VALUES (1,'a'), (2,'b')");
        }
        try (Connection target = sqlite(targetFile);
             Statement statement = target.createStatement()) {
            statement.execute("CREATE TABLE token_usage ("
                    + "id integer PRIMARY KEY AUTOINCREMENT, session_id text NOT NULL)");
        }

        try (Connection source = sqlite(sourceFile);
             Connection target = sqlite(targetFile)) {
            SqliteToTargetCopier.Report report = SqliteToTargetCopier.copy(source, target);
            assertEquals(2, report.copied());

            try (Statement write = target.createStatement()) {
                write.execute("INSERT INTO token_usage (session_id) VALUES ('c')");
            }
            try (Statement read = target.createStatement();
                 ResultSet rs = read.executeQuery("SELECT id FROM token_usage WHERE session_id = 'c'")) {
                assertTrue(rs.next());
                assertEquals(3, rs.getInt(1), "显式 rowid 搬行后 SQLite 自己把序列抬到了 3");
            }
        }
    }

    @Test
    @DisplayName("真库回归：PG 搬行后拨正序列，自增插入不再撞 token_usage 那类主键冲突")
    void postgresResyncFixesDuplicateKey() throws Exception {
        String url = System.getenv("AGENT_TEST_PG_URL");
        Assumptions.assumeTrue(url != null && !url.isBlank(),
                "未提供 AGENT_TEST_PG_URL（如 jdbc:postgresql://127.0.0.1:5432/postgres?user=postgres&password=pg），跳过真库回归");

        String table = "seq_sync_probe";
        try (Connection target = DriverManager.getConnection(url);
             Statement statement = target.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS " + table);
            try {
                statement.execute("CREATE TABLE " + table
                        + " (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text)");
                // 模拟 SQLite → PG 搬行：带显式 id 插入，序列不会跟着走
                statement.execute("INSERT INTO " + table + " (id, note) VALUES (1,'a'),(2,'b'),(3,'c')");

                assertEquals(1, IdentitySequenceSync.sync(target, table), "token_usage 这类表只有一个自增列");

                try (ResultSet rs = statement.executeQuery(
                        "INSERT INTO " + table + " (note) VALUES ('d') RETURNING id")) {
                    assertTrue(rs.next());
                    assertEquals(4, rs.getLong(1), "拨正后自增插入应接在 MAX(id)=3 后面");
                }
            } finally {
                statement.execute("DROP TABLE IF EXISTS " + table);
            }
        }
    }

    private static Connection sqlite(Path file) throws Exception {
        return DriverManager.getConnection("jdbc:sqlite:" + file);
    }
}
